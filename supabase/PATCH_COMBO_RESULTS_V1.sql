-- EVE Football Scanner — COMBO RESULTS V1
-- Run once in the dedicated eve-football-scanner Supabase project.
-- Permanently freezes Combo Lab recommendations and exposes single/double/treble outcomes.

create table if not exists public.combo_pick_log (
  id bigint generated by default as identity primary key,
  combo_recommendation_id uuid not null references public.combo_recommendations(id) on delete cascade,
  fixture_id uuid not null references public.fixtures(id) on delete cascade,
  model_version text not null,
  sample_size smallint not null default 0,
  singles jsonb not null default '[]'::jsonb,
  doubles jsonb not null default '[]'::jsonb,
  treble jsonb,
  data_quality smallint not null default 0,
  captured_at timestamptz not null default now(),
  unique(fixture_id, model_version)
);

create index if not exists combo_pick_log_fixture_idx on public.combo_pick_log(fixture_id);
create index if not exists combo_pick_log_captured_idx on public.combo_pick_log(captured_at desc);

alter table public.combo_pick_log enable row level security;

do $$ begin
  create policy "public read combo pick log"
  on public.combo_pick_log for select to anon, authenticated
  using (true);
exception when duplicate_object then null; end $$;

grant select on public.combo_pick_log to anon, authenticated;

create or replace function public.capture_combo_pick()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.model_version = 'v1-combo-research' and new.sample_size >= 10 then
    insert into public.combo_pick_log (
      combo_recommendation_id, fixture_id, model_version, sample_size,
      singles, doubles, treble, data_quality, captured_at
    ) values (
      new.id, new.fixture_id, new.model_version, new.sample_size,
      new.singles, new.doubles, new.treble, new.data_quality,
      coalesce(new.calculated_at, now())
    )
    on conflict (fixture_id, model_version) do nothing;
  end if;
  return new;
end;
$$;

drop trigger if exists capture_combo_pick_trigger on public.combo_recommendations;
create trigger capture_combo_pick_trigger
after insert or update on public.combo_recommendations
for each row execute function public.capture_combo_pick();

-- Backfill Combo Lab recommendations already produced since the project began.
insert into public.combo_pick_log (
  combo_recommendation_id, fixture_id, model_version, sample_size,
  singles, doubles, treble, data_quality, captured_at
)
select
  cr.id, cr.fixture_id, cr.model_version, cr.sample_size,
  cr.singles, cr.doubles, cr.treble, cr.data_quality, cr.calculated_at
from public.combo_recommendations cr
where cr.model_version = 'v1-combo-research'
  and cr.sample_size >= 10
on conflict (fixture_id, model_version) do nothing;

-- Combo result rows are calculated from the frozen recommendation and actual match data.
-- A double/treble only wins if every leg wins. Missing card/corner/half-time data stays awaiting_data.
create or replace view public.combo_result_log
with (security_invoker = true)
as
with combo_items as (
  select
    cpl.id as combo_log_id,
    cpl.fixture_id,
    cpl.sample_size,
    cpl.data_quality,
    cpl.captured_at,
    'single'::text as combo_type,
    x.ord::integer as position,
    array[x.item->>'key']::text[] as leg_keys,
    array[x.item->>'selection']::text[] as leg_labels,
    nullif(x.item->>'probability','')::numeric as historical_probability
  from public.combo_pick_log cpl
  cross join lateral jsonb_array_elements(cpl.singles) with ordinality as x(item,ord)

  union all

  select
    cpl.id,
    cpl.fixture_id,
    cpl.sample_size,
    cpl.data_quality,
    cpl.captured_at,
    'double'::text,
    x.ord::integer,
    array(select jsonb_array_elements_text(x.item->'keys')),
    array(select jsonb_array_elements_text(x.item->'legs')),
    nullif(x.item->>'probability','')::numeric
  from public.combo_pick_log cpl
  cross join lateral jsonb_array_elements(cpl.doubles) with ordinality as x(item,ord)

  union all

  select
    cpl.id,
    cpl.fixture_id,
    cpl.sample_size,
    cpl.data_quality,
    cpl.captured_at,
    'treble'::text,
    1,
    array(select jsonb_array_elements_text(cpl.treble->'keys')),
    array(select jsonb_array_elements_text(cpl.treble->'legs')),
    nullif(cpl.treble->>'probability','')::numeric
  from public.combo_pick_log cpl
  where cpl.treble is not null
    and jsonb_typeof(cpl.treble) = 'object'
),
base as (
  select
    ci.*,
    f.status as fixture_status,
    f.kickoff,
    f.home_goals,
    f.away_goals,
    f.half_time_home_goals,
    f.half_time_away_goals,
    f.league_id,
    f.home_team_id,
    f.away_team_id,
    hs.yellow_cards as home_yellow_cards,
    aw.yellow_cards as away_yellow_cards,
    hs.corners as home_corners,
    aw.corners as away_corners
  from combo_items ci
  join public.fixtures f on f.id = ci.fixture_id
  left join public.team_match_stats hs on hs.fixture_id = f.id and hs.team_id = f.home_team_id
  left join public.team_match_stats aw on aw.fixture_id = f.id and aw.team_id = f.away_team_id
),
evaluated as (
  select
    b.*,
    e.has_missing,
    e.all_hit
  from base b
  left join lateral (
    select
      bool_or(z.hit is null) as has_missing,
      bool_and(coalesce(z.hit,false)) as all_hit
    from (
      select case k
        when 'over_1_5' then
          case when b.home_goals is null or b.away_goals is null then null
               else (b.home_goals + b.away_goals >= 2) end
        when 'second_half_0_5' then
          case when b.home_goals is null or b.away_goals is null or b.half_time_home_goals is null or b.half_time_away_goals is null then null
               else ((b.home_goals + b.away_goals) - (b.half_time_home_goals + b.half_time_away_goals) >= 1) end
        when 'btts_yes' then
          case when b.home_goals is null or b.away_goals is null then null
               else (b.home_goals > 0 and b.away_goals > 0) end
        when 'first_half_0_5' then
          case when b.half_time_home_goals is null or b.half_time_away_goals is null then null
               else (b.half_time_home_goals + b.half_time_away_goals >= 1) end
        when 'match_cards_3_5' then
          case when b.home_yellow_cards is null or b.away_yellow_cards is null then null
               else (b.home_yellow_cards + b.away_yellow_cards >= 4) end
        when 'match_corners_8_5' then
          case when b.home_corners is null or b.away_corners is null then null
               else (b.home_corners + b.away_corners >= 9) end
        else null
      end as hit
      from unnest(b.leg_keys) as k
    ) z
  ) e on true
)
select
  (e.combo_log_id::text || '-' || e.combo_type || '-' || e.position::text) as id,
  e.combo_log_id as "comboLogId",
  e.fixture_id as "fixtureId",
  e.combo_type as "comboType",
  e.position,
  e.leg_keys as "legKeys",
  e.leg_labels as "legLabels",
  e.historical_probability as "historicalProbability",
  e.sample_size as "sampleSize",
  e.data_quality as "dataQuality",
  e.captured_at as "capturedAt",
  c.name as country,
  l.name as league,
  ht.name as "homeTeam",
  at.name as "awayTeam",
  e.kickoff as "kickoffUtc",
  e.fixture_status as "fixtureStatus",
  e.home_goals as "homeGoals",
  e.away_goals as "awayGoals",
  case
    when e.fixture_status <> 'finished' then 'pending'
    when coalesce(e.has_missing,true) then 'awaiting_data'
    when e.all_hit then 'win'
    else 'loss'
  end as outcome
from evaluated e
join public.leagues l on l.id = e.league_id
join public.countries c on c.id = l.country_id
join public.teams ht on ht.id = e.home_team_id
join public.teams at on at.id = e.away_team_id
order by e.kickoff desc, e.combo_type, e.position;

grant select on public.combo_result_log to anon, authenticated;

-- The result view needs read access to completed compact team stats in order to settle card/corner legs.
do $$ begin
  create policy "public read completed team match stats"
  on public.team_match_stats for select to anon, authenticated
  using (
    exists (
      select 1 from public.fixtures f
      where f.id = team_match_stats.fixture_id
        and f.status = 'finished'
    )
  );
exception when duplicate_object then null; end $$;

grant select on public.team_match_stats to anon, authenticated;

revoke all on function public.capture_combo_pick() from public;
revoke all on function public.capture_combo_pick() from anon;
revoke all on function public.capture_combo_pick() from authenticated;

comment on table public.combo_pick_log is 'Permanent first-seen snapshot of each live Combo Lab recommendation so results cannot be rewritten later.';
comment on view public.combo_result_log is 'Single, double and treble Combo Lab results with separate historical probabilities and live outcomes.';

select 'EVE Combo Results V1 patch complete' as status;