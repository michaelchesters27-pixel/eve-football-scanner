-- EVE Football Scanner — RESULTS LOG V1
-- Run once in the dedicated eve-football-scanner Supabase project.
-- Purpose: permanently remember every calibrated pick EVE actually publishes,
-- settle it from completed match data, and expose a public results page with hit rate.

create table if not exists public.scanner_pick_log (
  id bigint generated by default as identity primary key,
  prediction_id uuid not null unique references public.predictions(id) on delete cascade,
  fixture_id uuid not null references public.fixtures(id) on delete cascade,
  model_version text not null,
  source_page text not null check (source_page in ('best_bets','market_lab')),
  market text not null,
  selection text not null,
  confidence smallint not null check (confidence between 0 and 100),
  grade text not null,
  data_quality smallint not null check (data_quality between 0 and 100),
  fair_probability numeric(6,5),
  first_published_at timestamptz not null default now()
);

create index if not exists scanner_pick_log_fixture_idx on public.scanner_pick_log(fixture_id);
create index if not exists scanner_pick_log_published_idx on public.scanner_pick_log(first_published_at desc);

alter table public.scanner_pick_log enable row level security;

do $$ begin
  create policy "public read scanner pick log"
  on public.scanner_pick_log for select to anon, authenticated
  using (true);
exception when duplicate_object then null; end $$;

grant select on public.scanner_pick_log to anon, authenticated;

-- Freeze the first version of a pick when the calibrated engine publishes it.
-- If a later lineup/referee refresh suppresses it, the historical record is retained.
create or replace function public.capture_scanner_pick()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.publish_status = 'published'
     and new.model_version in ('v0-research','v1-expanded-research') then
    insert into public.scanner_pick_log (
      prediction_id, fixture_id, model_version, source_page, market, selection,
      confidence, grade, data_quality, fair_probability, first_published_at
    ) values (
      new.id,
      new.fixture_id,
      new.model_version,
      case when new.model_version = 'v0-research' then 'best_bets' else 'market_lab' end,
      new.market,
      new.selection,
      new.confidence,
      new.grade,
      new.data_quality,
      new.fair_probability,
      coalesce(new.generated_at, now())
    )
    on conflict (prediction_id) do nothing;
  end if;
  return new;
end;
$$;

drop trigger if exists capture_scanner_pick_trigger on public.predictions;
create trigger capture_scanner_pick_trigger
after insert or update of publish_status on public.predictions
for each row execute function public.capture_scanner_pick();

-- Backfill the picks that are already in the database from the first days of EVE.
insert into public.scanner_pick_log (
  prediction_id, fixture_id, model_version, source_page, market, selection,
  confidence, grade, data_quality, fair_probability, first_published_at
)
select
  p.id,
  p.fixture_id,
  p.model_version,
  case when p.model_version = 'v0-research' then 'best_bets' else 'market_lab' end,
  p.market,
  p.selection,
  p.confidence,
  p.grade,
  p.data_quality,
  p.fair_probability,
  p.generated_at
from public.predictions p
where p.publish_status = 'published'
  and p.model_version in ('v0-research','v1-expanded-research')
on conflict (prediction_id) do nothing;

-- Settle every supported logged pick using the actual completed match figures.
-- Missing card/corner/half-time data is NOT treated as a loss: it stays pending
-- until the underlying match data exists.
create or replace function public.settle_scanner_results()
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  affected integer := 0;
begin
  with calculated as (
    select
      spl.prediction_id,
      case
        when fs.selection_key = 'home_cards_1_5' and hs.yellow_cards is not null
          then case when hs.yellow_cards >= 2 then 'win' else 'loss' end
        when fs.selection_key = 'away_cards_1_5' and aw.yellow_cards is not null
          then case when aw.yellow_cards >= 2 then 'win' else 'loss' end
        when fs.selection_key = 'home_corners_4_5' and hs.corners is not null
          then case when hs.corners >= 5 then 'win' else 'loss' end
        when fs.selection_key = 'away_corners_4_5' and aw.corners is not null
          then case when aw.corners >= 5 then 'win' else 'loss' end
        when fs.selection_key = 'over_1_5' and f.home_goals is not null and f.away_goals is not null
          then case when f.home_goals + f.away_goals >= 2 then 'win' else 'loss' end
        when fs.selection_key = 'second_half_0_5'
          and f.home_goals is not null and f.away_goals is not null
          and f.half_time_home_goals is not null and f.half_time_away_goals is not null
          then case when (f.home_goals + f.away_goals) - (f.half_time_home_goals + f.half_time_away_goals) >= 1 then 'win' else 'loss' end

        when fs.selection_key = 'btts_yes' and f.home_goals is not null and f.away_goals is not null
          then case when f.home_goals > 0 and f.away_goals > 0 then 'win' else 'loss' end
        when fs.selection_key = 'home_goals_0_5' and f.home_goals is not null
          then case when f.home_goals >= 1 then 'win' else 'loss' end
        when fs.selection_key = 'away_goals_0_5' and f.away_goals is not null
          then case when f.away_goals >= 1 then 'win' else 'loss' end
        when fs.selection_key = 'home_goals_1_5' and f.home_goals is not null
          then case when f.home_goals >= 2 then 'win' else 'loss' end
        when fs.selection_key = 'away_goals_1_5' and f.away_goals is not null
          then case when f.away_goals >= 2 then 'win' else 'loss' end
        when fs.selection_key = 'first_half_0_5'
          and f.half_time_home_goals is not null and f.half_time_away_goals is not null
          then case when f.half_time_home_goals + f.half_time_away_goals >= 1 then 'win' else 'loss' end
        when fs.selection_key = 'match_cards_3_5' and hs.yellow_cards is not null and aw.yellow_cards is not null
          then case when hs.yellow_cards + aw.yellow_cards >= 4 then 'win' else 'loss' end
        when fs.selection_key = 'match_corners_8_5' and hs.corners is not null and aw.corners is not null
          then case when hs.corners + aw.corners >= 9 then 'win' else 'loss' end
        else null
      end as outcome
    from public.scanner_pick_log spl
    join public.predictions p on p.id = spl.prediction_id
    join public.feature_snapshots fs on fs.id = p.feature_snapshot_id
    join public.fixtures f on f.id = spl.fixture_id and f.status = 'finished'
    left join public.team_match_stats hs on hs.fixture_id = f.id and hs.team_id = f.home_team_id
    left join public.team_match_stats aw on aw.fixture_id = f.id and aw.team_id = f.away_team_id
  )
  insert into public.prediction_results (prediction_id, outcome, settled_at)
  select prediction_id, outcome, now()
  from calculated
  where outcome is not null
  on conflict (prediction_id) do update
  set outcome = excluded.outcome,
      settled_at = excluded.settled_at;

  get diagnostics affected = row_count;
  return affected;
end;
$$;

-- Results already in prediction_results remain public if they belong to a logged EVE pick,
-- even if a later re-analysis suppressed the current prediction.
do $$ begin
  create policy "public read logged scanner results"
  on public.prediction_results for select to anon, authenticated
  using (
    exists (
      select 1 from public.scanner_pick_log spl
      where spl.prediction_id = prediction_results.prediction_id
    )
  );
exception when duplicate_object then null; end $$;

create or replace view public.scanner_result_log
with (security_invoker = true)
as
select
  spl.id,
  spl.prediction_id as "predictionId",
  spl.fixture_id as "fixtureId",
  spl.source_page as "sourcePage",
  spl.model_version as "modelVersion",
  c.name as country,
  l.name as league,
  ht.name as "homeTeam",
  at.name as "awayTeam",
  f.kickoff as "kickoffUtc",
  spl.market,
  spl.selection,
  spl.confidence,
  spl.grade,
  spl.data_quality as "dataQuality",
  spl.fair_probability as "fairProbability",
  spl.first_published_at as "firstPublishedAt",
  f.status as "fixtureStatus",
  f.home_goals as "homeGoals",
  f.away_goals as "awayGoals",
  case
    when pr.outcome is not null then pr.outcome
    when f.status = 'finished' then 'awaiting_data'
    else 'pending'
  end as outcome,
  pr.settled_at as "settledAt"
from public.scanner_pick_log spl
join public.fixtures f on f.id = spl.fixture_id
join public.leagues l on l.id = f.league_id
join public.countries c on c.id = l.country_id
join public.teams ht on ht.id = f.home_team_id
join public.teams at on at.id = f.away_team_id
left join public.prediction_results pr on pr.prediction_id = spl.prediction_id
order by f.kickoff desc, spl.confidence desc;

grant select on public.scanner_result_log to anon, authenticated;

revoke all on function public.capture_scanner_pick() from public;
revoke all on function public.capture_scanner_pick() from anon;
revoke all on function public.capture_scanner_pick() from authenticated;
revoke all on function public.settle_scanner_results() from public;
revoke all on function public.settle_scanner_results() from anon;
revoke all on function public.settle_scanner_results() from authenticated;

comment on table public.scanner_pick_log is 'Permanent audit log of every calibrated EVE pick that reached published status. A pick stays in history even if later match-day reanalysis suppresses it.';
comment on function public.settle_scanner_results() is 'Settles logged core and expanded EVE picks from completed match data. Missing required statistics remain pending rather than becoming false losses.';
comment on view public.scanner_result_log is 'Public chronological results feed used by the Results page. Win percentage excludes pending/awaiting-data rows.';

-- Immediately settle any completed picks already stored from the project so far.
select public.settle_scanner_results() as backfilled_results;
select 'EVE Results Log V1 patch complete' as status;
