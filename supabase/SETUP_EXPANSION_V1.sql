create view public.scanner_best_bets
with (security_invoker = true)
as
select
  p.id,
  f.id as "fixtureId",
  c.name as country,
  l.name as league,
  ht.name as "homeTeam",
  at.name as "awayTeam",
  to_char(f.kickoff at time zone 'Europe/London', 'HH24:MI') as kickoff,
  f.kickoff as "kickoffUtc",
  p.market,
  p.selection,
  p.confidence,
  p.grade,
  p.data_quality as "dataQuality",
  p.evidence,
  case when r.id is null then null else jsonb_build_object('name',r.name,'cardsPerMatch',rp.yellow_cards_per_match,'foulsPerMatch',rp.fouls_per_match) end as referee,
  case when p.fair_probability is null then null else round((p.fair_probability * 100)::numeric, 1) end as "fairProbability",
  case when p.fair_probability is null or p.fair_probability <= 0 then null else round((1 / p.fair_probability)::numeric, 2) end as "fairOdds",
  bo.bookmaker as "bestBookmaker",
  bo.decimal_odds as "bestOdds",
  bo.captured_at as "oddsCapturedAt",
  case when bo.decimal_odds is null then null else round((100 / bo.decimal_odds)::numeric, 1) end as "impliedProbability",
  case when bo.decimal_odds is null or p.fair_probability is null then null else round(((p.fair_probability - (1 / bo.decimal_odds)) * 100)::numeric, 1) end as "edgePct",
  case when bo.decimal_odds is null or p.fair_probability is null then null else round(((p.fair_probability * bo.decimal_odds - 1) * 100)::numeric, 1) end as "expectedValuePct",
  case
    when p.fair_probability is null then 'uncalibrated'
    when bo.decimal_odds is null then 'waiting'
    when (p.fair_probability - (1 / bo.decimal_odds)) >= 0.07 and (p.fair_probability * bo.decimal_odds - 1) >= 0.10 then 'strong'
    when (p.fair_probability - (1 / bo.decimal_odds)) >= 0.05 and (p.fair_probability * bo.decimal_odds - 1) >= 0.05 then 'value'
    else 'no_value'
  end as "valueStatus"
from public.predictions p
join public.fixtures f on f.id = p.fixture_id
join public.leagues l on l.id = f.league_id
join public.countries c on c.id = l.country_id
join public.teams ht on ht.id = f.home_team_id
join public.teams at on at.id = f.away_team_id
left join public.referees r on r.id = f.referee_id
left join lateral (
  select yellow_cards_per_match, fouls_per_match
  from public.referee_profiles rp0
  where rp0.referee_id = r.id
  order by rp0.as_of_date desc
  limit 1
) rp on true
left join lateral (
  select os.bookmaker, os.decimal_odds, os.captured_at
  from public.odds_snapshots os
  where os.prediction_id = p.id and os.captured_at >= now() - interval '8 hours'
  order by os.decimal_odds desc, os.captured_at desc
  limit 1
) bo on true
where p.publish_status = 'published'
  and p.model_version = 'v0-research'
  and f.status in ('scheduled','live')
  and f.kickoff >= now() - interval '3 hours'
order by p.confidence desc;

create or replace view public.scanner_expanded_markets
with (security_invoker = true)
as
select
  p.id,
  f.id as "fixtureId",
  c.name as country,
  l.name as league,
  ht.name as "homeTeam",
  at.name as "awayTeam",
  to_char(f.kickoff at time zone 'Europe/London', 'HH24:MI') as kickoff,
  f.kickoff as "kickoffUtc",
  p.market,
  p.selection,
  p.confidence,
  p.grade,
  p.data_quality as "dataQuality",
  p.evidence,
  fs.selection_key as "selectionKey",
  fs.features,
  case when r.id is null then null else jsonb_build_object('name',r.name,'cardsPerMatch',rp.yellow_cards_per_match,'matchesSample',rp.matches_sample) end as referee,
  coalesce(mmc.lineups_confirmed,false) as "lineupsConfirmed",
  coalesce(mmc.referee_confirmed,false) as "refereeConfirmed"
from public.predictions p
join public.feature_snapshots fs on fs.id = p.feature_snapshot_id
join public.fixtures f on f.id = p.fixture_id
join public.leagues l on l.id = f.league_id
join public.countries c on c.id = l.country_id
join public.teams ht on ht.id = f.home_team_id
join public.teams at on at.id = f.away_team_id
left join public.manual_match_context mmc on mmc.fixture_id = f.id
left join public.referees r on r.id = f.referee_id
left join lateral (
  select yellow_cards_per_match, matches_sample
  from public.referee_profiles rp0
  where rp0.referee_id = r.id
  order by rp0.as_of_date desc
  limit 1
) rp on true
where p.model_version = 'v1-expanded-research'
  and p.publish_status = 'published'
  and f.status in ('scheduled','live')
  and f.kickoff >= now() - interval '3 hours'
order by p.confidence desc;

create or replace view public.fixture_setup_board
with (security_invoker = true)
as
select
  f.id as "fixtureId",
  c.name as country,
  l.name as league,
  ht.id as "homeTeamId",
  ht.name as "homeTeam",
  at.id as "awayTeamId",
  at.name as "awayTeam",
  f.kickoff,
  r.name as referee,
  coalesce(mmc.referee_confirmed,false) as "refereeConfirmed",
  coalesce(mmc.lineups_confirmed,false) as "lineupsConfirmed",
  count(fl.id) filter (where fl.team_id = f.home_team_id and fl.is_starting) as "homeStarters",
  count(fl.id) filter (where fl.team_id = f.away_team_id and fl.is_starting) as "awayStarters"
from public.fixtures f
join public.leagues l on l.id = f.league_id
join public.countries c on c.id = l.country_id
join public.teams ht on ht.id = f.home_team_id
join public.teams at on at.id = f.away_team_id
left join public.referees r on r.id = f.referee_id
left join public.manual_match_context mmc on mmc.fixture_id = f.id
left join public.fixture_lineups fl on fl.fixture_id = f.id
where f.status in ('scheduled','live')
  and f.kickoff >= now() - interval '3 hours'
  and f.kickoff < now() + interval '8 days'
group by f.id,c.name,l.name,ht.id,ht.name,at.id,at.name,f.kickoff,r.name,mmc.referee_confirmed,mmc.lineups_confirmed
order by f.kickoff;

create or replace view public.fixture_player_outlook
with (security_invoker = true)
as
select
  fl.fixture_id as "fixtureId",
  fl.team_id as "teamId",
  t.name as "teamName",
  p.id as "playerId",
  p.name,
  coalesce(fl.position,p.position) as position,
  fl.is_starting as "isStarting",
  form.matches as "matchesSample",
  form.avg_minutes as "avgMinutes",
  form.avg_shots as "avgShots",
  form.avg_sot as "avgShotsOnTarget",
  form.avg_goals as "avgGoals",
  form.avg_cards as "avgYellowCards"
from public.fixture_lineups fl
join public.fixtures current_fixture on current_fixture.id = fl.fixture_id
join public.players p on p.id = fl.player_id
join public.teams t on t.id = fl.team_id
left join lateral (
  select
    count(*)::integer as matches,
    round(avg(x.minutes)::numeric,1) as avg_minutes,
    round(avg(x.shots)::numeric,2) as avg_shots,
    round(avg(x.shots_on_target)::numeric,2) as avg_sot,
    round(avg(x.goals)::numeric,2) as avg_goals,
    round(avg(x.yellow_cards)::numeric,2) as avg_cards
  from (
    select pms.*
    from public.player_match_stats pms
    join public.fixtures pf on pf.id = pms.fixture_id
    where pms.player_id = p.id and pf.kickoff < current_fixture.kickoff and pf.status = 'finished'
    order by pf.kickoff desc
    limit 10
  ) x
) form on true
where fl.is_starting = true;

