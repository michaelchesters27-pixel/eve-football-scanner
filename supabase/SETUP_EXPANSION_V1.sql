create table if not exists public.players (
  id uuid primary key default gen_random_uuid(),
  source text not null default 'fotmob',
  source_player_id text,
  name text not null,
  current_team_id uuid references public.teams(id) on delete set null,
  position text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(source, source_player_id)
);

create table if not exists public.player_match_stats (
  id bigint generated by default as identity primary key,
  fixture_id uuid not null references public.fixtures(id) on delete cascade,
  player_id uuid not null references public.players(id) on delete cascade,
  team_id uuid not null references public.teams(id) on delete cascade,
  started boolean not null default false,
  minutes smallint,
  shots smallint,
  shots_on_target smallint,
  goals smallint,
  assists smallint,
  yellow_cards smallint,
  red_cards smallint,
  fouls_committed smallint,
  fouls_won smallint,
  xg numeric(7,3),
  xa numeric(7,3),
  source text not null default 'fotmob',
  created_at timestamptz not null default now(),
  unique(fixture_id, player_id)
);

create table if not exists public.fixture_lineups (
  id bigint generated by default as identity primary key,
  fixture_id uuid not null references public.fixtures(id) on delete cascade,
  team_id uuid not null references public.teams(id) on delete cascade,
  player_id uuid not null references public.players(id) on delete cascade,
  is_starting boolean not null default true,
  shirt_number smallint,
  position text,
  source text not null default 'manual',
  confirmed_at timestamptz not null default now(),
  unique(fixture_id, player_id, source)
);

create table if not exists public.manual_match_context (
  fixture_id uuid primary key references public.fixtures(id) on delete cascade,
  referee_name text,
  referee_confirmed boolean not null default false,
  lineups_confirmed boolean not null default false,
  notes text,
  confirmed_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.combo_recommendations (
  id uuid primary key default gen_random_uuid(),
  fixture_id uuid not null references public.fixtures(id) on delete cascade,
  model_version text not null default 'v1-combo-research',
  sample_size smallint not null default 0,
  singles jsonb not null default '[]'::jsonb,
  doubles jsonb not null default '[]'::jsonb,
  treble jsonb,
  explanation text,
  data_quality smallint not null default 0 check (data_quality between 0 and 100),
  calculated_at timestamptz not null default now(),
  unique(fixture_id, model_version)
);

create index if not exists players_team_idx on public.players(current_team_id);
