create or replace function public.settle_expanded_predictions()
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare affected integer := 0;
begin
  insert into public.prediction_results (prediction_id, outcome, settled_at)
  select p.id,
    case
      when fs.selection_key = 'btts_yes' then case when coalesce(f.home_goals,0) > 0 and coalesce(f.away_goals,0) > 0 then 'win' else 'loss' end
      when fs.selection_key = 'home_goals_0_5' then case when coalesce(f.home_goals,0) >= 1 then 'win' else 'loss' end
      when fs.selection_key = 'away_goals_0_5' then case when coalesce(f.away_goals,0) >= 1 then 'win' else 'loss' end
      when fs.selection_key = 'home_goals_1_5' then case when coalesce(f.home_goals,0) >= 2 then 'win' else 'loss' end
      when fs.selection_key = 'away_goals_1_5' then case when coalesce(f.away_goals,0) >= 2 then 'win' else 'loss' end
      when fs.selection_key = 'first_half_0_5' then case when coalesce(f.half_time_home_goals,0) + coalesce(f.half_time_away_goals,0) >= 1 then 'win' else 'loss' end
      when fs.selection_key = 'match_cards_3_5' then case when coalesce(hs.yellow_cards,0) + coalesce(aw.yellow_cards,0) >= 4 then 'win' else 'loss' end
      when fs.selection_key = 'match_corners_8_5' then case when coalesce(hs.corners,0) + coalesce(aw.corners,0) >= 9 then 'win' else 'loss' end
      else 'void'
    end,
    now()
  from public.predictions p
  join public.feature_snapshots fs on fs.id = p.feature_snapshot_id
  join public.fixtures f on f.id = p.fixture_id and f.status = 'finished'
  left join public.team_match_stats hs on hs.fixture_id = f.id and hs.team_id = f.home_team_id
  left join public.team_match_stats aw on aw.fixture_id = f.id and aw.team_id = f.away_team_id
  left join public.prediction_results existing on existing.prediction_id = p.id
  where existing.prediction_id is null and p.model_version = 'v1-expanded-research';
  get diagnostics affected = row_count;
  return affected;
end;
$$;

