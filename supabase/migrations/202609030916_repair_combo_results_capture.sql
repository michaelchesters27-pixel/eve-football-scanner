-- Production repair for Combo Results.
-- Preserve legacy result history, add permanent first-seen combo snapshots, and dynamically settle outcomes.
-- Important: combo_pick_log deliberately has NO cascade FK to combo_recommendations because safe Combo Lab rebuilds delete recommendations.

alter table public.combo_result_log rename to combo_result_log_legacy;
revoke all on public.combo_result_log_legacy from anon, authenticated;

create table public.combo_pick_log (
  id bigint generated by default as identity primary key,
  combo_recommendation_id uuid not null,
  fixture_id uuid not null references public.fixtures(id) on delete restrict,
  model_version text not null,
  sample_size smallint not null default 0,
  singles jsonb not null default '[]'::jsonb,
  doubles jsonb not null default '[]'::jsonb,
  treble jsonb,
  data_quality smallint not null default 0,
  captured_at timestamptz not null default now(),
  unique(fixture_id, model_version)
);
create index combo_pick_log_fixture_idx on public.combo_pick_log(fixture_id);
create index combo_pick_log_captured_idx on public.combo_pick_log(captured_at desc);
alter table public.combo_pick_log enable row level security;
revoke all on public.combo_pick_log from anon, authenticated;

select setval(
  pg_get_serial_sequence('public.combo_pick_log','id'),
  greatest(coalesce((select max("comboLogId") from public.combo_result_log_legacy),0) + 1, 1),
  false
);

create or replace function public.capture_combo_pick()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.model_version = 'v1-combo-research' and new.sample_size >= 10 then
    insert into public.combo_pick_log (
      combo_recommendation_id, fixture_id, model_version, sample_size,
      singles, doubles, treble, data_quality, captured_at
    ) values (
      new.id, new.fixture_id, new.model_version, new.sample_size,
      new.singles, new.doubles, new.treble, new.data_quality,
      coalesce(new.calculated_at, now())
    )
    on conflict (fixture_id, model_version) do nothing;
  end if;
  return new;
end;
$$;
revoke all on function public.capture_combo_pick() from public, anon, authenticated;

drop trigger if exists capture_combo_pick_trigger on public.combo_recommendations;
create trigger capture_combo_pick_trigger
after insert or update on public.combo_recommendations
for each row execute function public.capture_combo_pick();

insert into public.combo_pick_log (
  combo_recommendation_id, fixture_id, model_version, sample_size,
  singles, doubles, treble, data_quality, captured_at
)
select cr.id, cr.fixture_id, cr.model_version, cr.sample_size,
       cr.singles, cr.doubles, cr.treble, cr.data_quality, cr.calculated_at
from public.combo_recommendations cr
where cr.model_version = 'v1-combo-research'
  and cr.sample_size >= 10
  and not exists (
    select 1 from public.combo_result_log_legacy l
    where l."fixtureId" = cr.fixture_id
  )
on conflict (fixture_id, model_version) do nothing;

create view public.combo_result_log
with (security_invoker = false)
as
with new_items as (
  select cpl.id as combo_log_id, cpl.fixture_id, cpl.sample_size, cpl.data_quality, cpl.captured_at,
         'single'::text as combo_type, x.ord::integer as position,
         array[x.item->>'key']::text[] as leg_keys,
         array[x.item->>'selection']::text[] as leg_labels,
         nullif(x.item->>'probability','')::numeric as historical_probability
  from public.combo_pick_log cpl
  cross join lateral jsonb_array_elements(cpl.singles) with ordinality as x(item,ord)
  union all
  select cpl.id, cpl.fixture_id, cpl.sample_size, cpl.data_quality, cpl.captured_at,
         'double'::text, x.ord::integer,
         array(select jsonb_array_elements_text(x.item->'keys')),
         array(select jsonb_array_elements_text(x.item->'legs')),
         nullif(x.item->>'probability','')::numeric
  from public.combo_pick_log cpl
  cross join lateral jsonb_array_elements(cpl.doubles) with ordinality as x(item,ord)
  union all
  select cpl.id, cpl.fixture_id, cpl.sample_size, cpl.data_quality, cpl.captured_at,
         'treble'::text, 1,
         array(select jsonb_array_elements_text(cpl.treble->'keys')),
         array(select jsonb_array_elements_text(cpl.treble->'legs')),
         nullif(cpl.treble->>'probability','')::numeric
  from public.combo_pick_log cpl
  where cpl.treble is not null and jsonb_typeof(cpl.treble)='object'
),
frozen_items as (
  select l."comboLogId" as combo_log_id, l."fixtureId" as fixture_id,
         l."sampleSize" as sample_size, l."dataQuality" as data_quality, l."capturedAt" as captured_at,
         l."comboType" as combo_type, l.position, l."legKeys" as leg_keys, l."legLabels" as leg_labels,
         l."historicalProbability" as historical_probability
  from public.combo_result_log_legacy l
  union all
  select n.combo_log_id, n.fixture_id, n.sample_size, n.data_quality, n.captured_at,
         n.combo_type, n.position, n.leg_keys, n.leg_labels, n.historical_probability
  from new_items n
  where not exists (select 1 from public.combo_result_log_legacy l where l."fixtureId"=n.fixture_id)
),
base as (
  select fi.*, f.status as fixture_status, f.kickoff, f.home_goals, f.away_goals,
         f.half_time_home_goals, f.half_time_away_goals, f.league_id, f.home_team_id, f.away_team_id,
         f.updated_at as fixture_updated_at,
         hs.yellow_cards as home_yellow_cards, aw.yellow_cards as away_yellow_cards,
         hs.corners as home_corners, aw.corners as away_corners,
         hs.created_at as home_stats_created_at, aw.created_at as away_stats_created_at
  from frozen_items fi
  join public.fixtures f on f.id=fi.fixture_id
  left join public.team_match_stats hs on hs.fixture_id=f.id and hs.team_id=f.home_team_id
  left join public.team_match_stats aw on aw.fixture_id=f.id and aw.team_id=f.away_team_id
),
evaluated as (
  select b.*, e.has_missing, e.all_hit
  from base b
  left join lateral (
    select bool_or(z.hit is null) as has_missing,
           bool_and(coalesce(z.hit,false)) as all_hit
    from (
      select case k
        when 'over_1_5' then case when b.home_goals is null or b.away_goals is null then null else b.home_goals+b.away_goals>=2 end
        when 'second_half_0_5' then case when b.home_goals is null or b.away_goals is null or b.half_time_home_goals is null or b.half_time_away_goals is null then null else (b.home_goals+b.away_goals)-(b.half_time_home_goals+b.half_time_away_goals)>=1 end
        when 'btts_yes' then case when b.home_goals is null or b.away_goals is null then null else b.home_goals>0 and b.away_goals>0 end
        when 'first_half_0_5' then case when b.half_time_home_goals is null or b.half_time_away_goals is null then null else b.half_time_home_goals+b.half_time_away_goals>=1 end
        when 'match_cards_3_5' then case when b.home_yellow_cards is null or b.away_yellow_cards is null then null else b.home_yellow_cards+b.away_yellow_cards>=4 end
        when 'match_corners_8_5' then case when b.home_corners is null or b.away_corners is null then null else b.home_corners+b.away_corners>=9 end
        else null end as hit
      from unnest(b.leg_keys) as k
    ) z
  ) e on true
)
select
  e.combo_log_id::text||'-'||e.combo_type||'-'||e.position::text as id,
  e.combo_log_id as "comboLogId", e.fixture_id as "fixtureId", e.combo_type as "comboType", e.position,
  e.leg_keys as "legKeys", e.leg_labels as "legLabels", e.historical_probability as "historicalProbability",
  e.sample_size as "sampleSize", e.data_quality as "dataQuality", e.captured_at as "capturedAt",
  c.name as country, l.name as league, ht.name as "homeTeam", at.name as "awayTeam",
  e.kickoff as "kickoffUtc", e.fixture_status as "fixtureStatus", e.home_goals as "homeGoals", e.away_goals as "awayGoals",
  case when e.fixture_status<>'finished' then 'pending'
       when coalesce(e.has_missing,true) then 'awaiting_data'
       when e.all_hit then 'win' else 'loss' end as outcome,
  greatest(e.captured_at, coalesce(e.fixture_updated_at,e.captured_at),
           coalesce(e.home_stats_created_at,e.captured_at), coalesce(e.away_stats_created_at,e.captured_at)) as "refreshedAt"
from evaluated e
join public.leagues l on l.id=e.league_id
join public.countries c on c.id=l.country_id
join public.teams ht on ht.id=e.home_team_id
join public.teams at on at.id=e.away_team_id;

grant select on public.combo_result_log to anon, authenticated;

comment on table public.combo_pick_log is 'Permanent first-seen Combo Lab snapshots. Recommendation deletion cannot erase result history.';
comment on view public.combo_result_log is 'Combined legacy and durable Combo Lab result history, dynamically settled from current match data.';
